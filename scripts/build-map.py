#!/usr/bin/env python3
"""Generate src/data/germany-paths.js from public-domain Bundesländer GeoJSON.

Source: https://github.com/isellsoap/deutschlandGeoJSON (Unlicense / public domain)
Boundary data originally from the German federal agencies (BKG / GeoBasis-DE).

The GeoJSON is projected with an Albers equal-area conic (standard parallels
48N/54N, origin 51N/10E), simplified with Douglas–Peucker and emitted as one
SVG path per federal state, keyed by its two-letter code (BW, BY, ...).

Run: python3 scripts/build-map.py
"""

from __future__ import annotations

import json
import math
import urllib.request
from pathlib import Path

SRC_URL = (
    "https://raw.githubusercontent.com/isellsoap/deutschlandGeoJSON/main/"
    "2_bundeslaender/3_mittel.geo.json"
)
OUT = Path(__file__).resolve().parent.parent / "src" / "data" / "germany-paths.js"

# Douglas–Peucker tolerance, in projected units (the country is ~0.10 wide).
TOLERANCE = 0.0003

P1, P2, LAT0, LON0 = map(math.radians, (48.0, 54.0, 51.0, 10.0))
N = (math.sin(P1) + math.sin(P2)) / 2
C = math.cos(P1) ** 2 + 2 * N * math.sin(P1)
RHO0 = math.sqrt(C - 2 * N * math.sin(LAT0)) / N


def project(lon: float, lat: float) -> tuple[float, float]:
    """Albers -> SVG coordinates. y is negated because SVG grows downward, so
    north (smaller rho) must land at a smaller y."""
    lon, lat = math.radians(lon), math.radians(lat)
    rho = math.sqrt(C - 2 * N * math.sin(lat)) / N
    theta = N * (lon - LON0)
    return rho * math.sin(theta), rho * math.cos(theta) - RHO0


def simplify(points: list[tuple[float, float]], eps: float) -> list[tuple[float, float]]:
    if len(points) < 3:
        return points

    def dist2(p, a, b):
        (x, y), (x1, y1), (x2, y2) = p, a, b
        dx, dy = x2 - x1, y2 - y1
        if dx == 0 and dy == 0:
            return (x - x1) ** 2 + (y - y1) ** 2
        t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
        return (x - (x1 + t * dx)) ** 2 + (y - (y1 + t * dy)) ** 2

    stack = [(0, len(points) - 1)]
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    while stack:
        i, j = stack.pop()
        if j <= i + 1:
            continue
        idx, best = -1, -1.0
        for k in range(i + 1, j):
            d = dist2(points[k], points[i], points[j])
            if d > best:
                best, idx = d, k
        if best > eps * eps:
            keep[idx] = True
            stack += [(i, idx), (idx, j)]
    return [p for p, k in zip(points, keep) if k]


def main() -> None:
    with urllib.request.urlopen(SRC_URL, timeout=60) as resp:
        geo = json.load(resp)

    rings_by_state: dict[str, list[list[tuple[float, float]]]] = {}
    for feat in geo["features"]:
        code = feat["properties"]["id"].removeprefix("DE-")
        geom = feat["geometry"]
        polygons = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        rings = []
        for polygon in polygons:
            for ring in polygon:
                pts = simplify([project(x, y) for x, y in ring], TOLERANCE)
                if len(pts) >= 4:
                    rings.append(pts)
        rings_by_state[code] = rings

    xs = [x for rings in rings_by_state.values() for r in rings for x, _ in r]
    ys = [y for rings in rings_by_state.values() for r in rings for _, y in r]
    min_x, min_y = min(xs), min(ys)
    scale = 1000.0 / (max(xs) - min_x)
    width, height = 1000.0, round((max(ys) - min_y) * scale, 1)

    def to_path(rings):
        return "".join(
            "M" + " ".join(f"{round((x - min_x) * scale, 1):g},{round((y - min_y) * scale, 1):g}"
                          for x, y in r) + "Z"
            for r in rings
        )

    lines = [
        "// Generated by scripts/build-map.py — do not edit by hand.",
        "// Bundesländer boundaries: public domain (isellsoap/deutschlandGeoJSON).",
        f'export const VIEW_BOX = "0 0 {width:g} {height:g}";',
        "",
        "export const STATE_PATHS = {",
    ]
    for code in sorted(rings_by_state):
        lines.append(f'  {code}: "{to_path(rings_by_state[code])}",')
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines))
    points = sum(len(r) for rings in rings_by_state.values() for r in rings)
    print(f"wrote {OUT} — {len(rings_by_state)} states, {points} points, "
          f"{OUT.stat().st_size / 1024:.1f} KB, viewBox {lines[2].split(chr(34))[1]}")


if __name__ == "__main__":
    main()
